CREATE TABLE public_bank_plaza_metrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type text NOT NULL CHECK (source_type IN ('system', 'user_public')),
    source_id bigint NOT NULL,
    name text NOT NULL,
    description text,
    cover_image text,
    owner_id bigint,
    owner_label text NOT NULL,
    owner_avatar text,
    question_count_total bigint NOT NULL DEFAULT 0,
    plaza_board_id integer REFERENCES plaza_boards(id) ON DELETE SET NULL,
    is_featured boolean NOT NULL DEFAULT false,
    featured_weight integer NOT NULL DEFAULT 0,
    published_at timestamp without time zone,
    last_activity_at timestamp without time zone,
    join_count_total bigint NOT NULL DEFAULT 0,
    join_users_7d bigint NOT NULL DEFAULT 0,
    join_users_30d bigint NOT NULL DEFAULT 0,
    answer_count_7d bigint NOT NULL DEFAULT 0,
    answer_count_30d bigint NOT NULL DEFAULT 0,
    answer_users_7d bigint NOT NULL DEFAULT 0,
    answer_users_30d bigint NOT NULL DEFAULT 0,
    hot_score double precision NOT NULL DEFAULT 0,
    active_score double precision NOT NULL DEFAULT 0,
    recommended_score double precision NOT NULL DEFAULT 0,
    join_mode text NOT NULL DEFAULT 'free',
    join_note text NOT NULL DEFAULT '',
    allow_copy boolean NOT NULL DEFAULT true,
    share_count bigint NOT NULL DEFAULT 0,
    snapshot_generation bigint NOT NULL CHECK (snapshot_generation > 0),
    projection_digest char(64) NOT NULL DEFAULT repeat('0', 64)
        CHECK (projection_digest ~ '^[0-9a-f]{64}$'),
    updated_at timestamp without time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_public_bank_plaza_metric_source UNIQUE (source_type, source_id)
);

